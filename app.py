
import json
from pathlib import Path

import streamlit as st

st.set_page_config(
    page_title="Suspicious Message Classifier",
    page_icon="🔍",
    layout="centered"
)

st.title("Suspicious Message Classifier")

st.write(
    "An interactive prototype exploring how AI recommendations "
    "influence human decisions when identifying suspicious messages."
)

# Load predefined messages
messages_path = Path(__file__).parent / "messages.json"

with messages_path.open("r", encoding="utf-8") as file:
    messages = json.load(file)


# Initialise session state
if "initial_judgement" not in st.session_state:
    st.session_state.initial_judgement = None

if "ai_revealed" not in st.session_state:
    st.session_state.ai_revealed = False

if "final_submitted" not in st.session_state:
    st.session_state.final_submitted = False


def reset_decision():
    st.session_state.initial_judgement = None
    st.session_state.ai_revealed = False
    st.session_state.final_submitted = False


def start_again():
    reset_decision()

    message_id = st.session_state.selected_message["id"]

    st.session_state[f"judgement_{message_id}"] = None
    st.session_state.pop(f"evidence_{message_id}", None)
    st.session_state.pop(f"final_{message_id}", None)


st.subheader("Step 1: Review a Message")

selected_message = st.selectbox(
    "Choose a message to review:",
    messages,
    format_func=lambda message: message["title"],
    key="selected_message",
    on_change=reset_decision
)

st.markdown(f"**From:** {selected_message['sender']}")
st.markdown(f"**Subject:** {selected_message['title']}")

st.text_area(
    "Message content",
    value=selected_message["content"],
    height=150,
    disabled=True
)

st.subheader("Step 2: Make Your Initial Judgement")

initial_judgement = st.radio(
    "Do you think this message is safe or suspicious?",
    ["Safe", "Suspicious"],
    index=None,
    key=f"judgement_{selected_message['id']}",
    disabled=st.session_state.ai_revealed
)

if not st.session_state.ai_revealed:

    if st.button("Submit Initial Judgement"):

        if initial_judgement is None:
            st.warning(
                "Please select a classification before continuing."
            )
        else:
            st.session_state.initial_judgement = initial_judgement
            st.session_state.ai_revealed = True
            st.rerun()

else:

    st.success(
        f"Your initial judgement: "
        f"{st.session_state.initial_judgement}"
    )

    st.subheader("Step 3: AI Recommendation")

    st.caption(
        "Prototype simulation: The AI recommendation and confidence "
        "are predefined, not generated by a trained model."
    )

    ai_classification = selected_message["ai_classification"]
    ai_confidence = selected_message["ai_confidence"]

    st.info(f"AI recommendation: {ai_classification}")
    st.write(f"AI confidence: {ai_confidence}%")

    # Determine whether an intervention is necessary
    disagreement = (
        st.session_state.initial_judgement != ai_classification
    )

    low_confidence = ai_confidence < 70

    intervention_required = disagreement or low_confidence

    if intervention_required:

        st.subheader("Step 4: Review the Evidence")

        if disagreement:
            st.warning(
                "Your initial judgement differs from the AI "
                "recommendation. Review the message before deciding."
            )

        if low_confidence:
            st.warning(
                "The simulated AI has relatively low confidence "
                "in its recommendation."
            )

        st.write(
            "Before continuing, identify an observation "
            "that is relevant to your decision."
        )

        evidence = st.radio(
            "What do you notice about this message?",
            [
                "It creates urgency or pressure.",
                "It requests sensitive information or payment.",
                "The sender or link appears questionable.",
                "I cannot identify an obvious suspicious feature."
            ],
            index=None,
            key=f"evidence_{selected_message['id']}",
            disabled=st.session_state.final_submitted
        )

        evidence_reviewed = evidence is not None

    else:
        evidence_reviewed = True

    st.subheader("Step 5: Make Your Final Decision")

    final_judgement = st.radio(
        "After considering the AI recommendation, "
        "what is your final classification?",
        ["Safe", "Suspicious"],
        index=None,
        key=f"final_{selected_message['id']}",
        disabled=st.session_state.final_submitted
    )

    if not st.session_state.final_submitted:

        if st.button("Submit Final Decision"):

            if not evidence_reviewed:
                st.warning(
                    "Please review the message evidence "
                    "before submitting your final decision."
                )

            elif final_judgement is None:
                st.warning(
                    "Please select your final classification."
                )

            else:
                st.session_state.final_submitted = True
                st.rerun()

    else:

        actual_classification = selected_message[
            "actual_classification"
        ]

        st.subheader("Decision Summary")

        st.write(
            f"**Initial judgement:** "
            f"{st.session_state.initial_judgement}"
        )

        st.write(
            f"**AI recommendation:** {ai_classification}"
        )

        st.write(
            f"**Final judgement:** {final_judgement}"
        )

        st.write(
            f"**Scenario's intended classification:** "
            f"{actual_classification}"
        )

        if final_judgement == actual_classification:
            st.success(
                "Your final judgement matches the "
                "scenario's intended classification."
            )
        else:
            st.warning(
                "Your final judgement differs from the "
                "scenario's intended classification."
            )

    st.button(
        "Start Again",
        on_click=start_again
    )
